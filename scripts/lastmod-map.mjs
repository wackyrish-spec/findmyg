// Writes src/content/lastmod.json: each content source file's last real change date.
// Cloudflare builds from a shallow clone, so the sitemap can't read git history there; run this before
// committing a batch (npm run lastmod). Files with uncommitted changes get today's date.
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
const git = (...a) => execFileSync("git", a, { encoding: "utf8" }).trim();
const today = new Date().toISOString().slice(0, 10);
const dirty = new Set(execFileSync("git", ["status", "--porcelain"], { encoding: "utf8" }).split("\n").filter(Boolean).map((l) => l.slice(3)));
const files = ["data/garages.json", "src/content/intros.json", "src/pages/garage/[slug]/index.astro",
  ...["guides", "issues", "problems"].flatMap((d) => readdirSync(`src/content/${d}`).filter((f) => f.endsWith(".md")).map((f) => `src/content/${d}/${f}`)),
  ...readdirSync("src/pages").filter((f) => f.endsWith(".astro")).map((f) => `src/pages/${f}`)];
const map = { _why: "Generated by scripts/lastmod-map.mjs (npm run lastmod). Sitemap fallback when the build has no git history." };
for (const f of files.sort()) map[f] = dirty.has(f) ? today : git("log", "-1", "--format=%cs", "--", f) || today;
writeFileSync("src/content/lastmod.json", JSON.stringify(map, null, 2) + "\n");
console.log(`lastmod.json: ${files.length} files`);
